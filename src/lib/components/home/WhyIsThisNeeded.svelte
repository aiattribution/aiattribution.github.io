	<h1 class="section-title">Why is this needed?</h1>
	<p class="section-text">
		As generative AI use becomes more widespread and complex, new forms of transparency are needed
		to provide more granularity into how AI was used. For example, in a co-written article, was AI
		used to make minor wording revisions or generate new ideas? Did AI produce the majority of the
		article, or did it only modify a few sentences? Creators may also want to assert that AI was not
		used in their work.
	</p>
	<p class="section-text">
		Generic disclosures, e.g., “assisted by AI,” are no longer sufficient. Our goal is to develop
		open-source, detailed AI attribution methods that accurately represent creators’ ownership
		perceptions and provide consumers with more transparency to calibrate their trust. One approach
		we’ve devised is an attribution statement, inspired by the Creative Commons license and
		motivated by our research on users’ transparency needs in co-created work.
